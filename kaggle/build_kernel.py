"""Pack the repo code into one self-extracting Kaggle script (kaggle/kernel/run_aiups.py).

    python kaggle/build_kernel.py && kaggle kernels push -p kaggle/kernel
    kaggle kernels status sehajrsingh/ai-ups-cert-run_all
    kaggle kernels output sehajrsingh/ai-ups-cert-run_all -p kaggle/out
"""
import base64
import io
import json
import os
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "kaggle", "kernel")
os.makedirs(OUT, exist_ok=True)

buf = io.BytesIO()
with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
    z.write(os.path.join(ROOT, "run_all.py"), "run_all.py")
    for dp, _, fs in os.walk(os.path.join(ROOT, "src", "aiups")):
        for f in fs:
            if f.endswith(".py"):
                full = os.path.join(dp, f)
                z.write(full, os.path.relpath(full, ROOT))
payload = base64.b64encode(buf.getvalue()).decode()

script = f'''# Auto-generated by kaggle/build_kernel.py: runs ai-ups-cert run_all.py on Kaggle CPU.
import base64, io, os, subprocess, sys, zipfile, shutil
W = "/kaggle/working"
src = os.path.join(W, "repo")
os.makedirs(src, exist_ok=True)
zipfile.ZipFile(io.BytesIO(base64.b64decode("{payload}"))).extractall(src)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "pandapower"], check=False)
env = dict(os.environ, OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1", MKL_NUM_THREADS="1")
r = subprocess.run([sys.executable, "run_all.py"], cwd=src, env=env)
for d in ("results", "figures"):
    if os.path.isdir(os.path.join(src, d)):
        shutil.copytree(os.path.join(src, d), os.path.join(W, d), dirs_exist_ok=True)
shutil.rmtree(src, ignore_errors=True)
sys.exit(r.returncode)
'''
open(os.path.join(OUT, "run_aiups.py"), "w").write(script)
json.dump({
    "id": "sehajrsingh/ai-ups-cert-run-all",
    "title": "ai-ups-cert run_all",
    "code_file": "run_aiups.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": False,
    "enable_internet": True,
    "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
}, open(os.path.join(OUT, "kernel-metadata.json"), "w"), indent=2)
print("built", len(payload), "bytes of payload")
